#!/usr/bin/env python3
"""Bake the caption font into source/FontAtlas.cpp as a signed distance field.

The caption is the intro's white, loosely spaced condensed grotesque. The
original was Helios Condensed Light, a cheap Helvetica clone that nobody may
redistribute; Roboto Condensed (SIL Open Font License 1.1, its notice in
fonts/OFL.txt) at weight 300 is the open face nearest to it.

Each printable ASCII glyph (32..126) is drawn with its pen origin at the same
place in a CELL_W x CELL_H cell, at SUPER times the size, and its exact
Euclidean distance to the outline is taken there (scipy's EDT, both sides),
then sampled at the cells' pixel centres. A texel is

    0.5 + d / ( 2 * SPREAD )      clamped to 0..1, d in cell pixels, + inside

so 0.5 is the outline and the field reaches SPREAD pixels either side: the
glow is read from the same texture as the letter. The table is written as
bytes; MSVC refuses a string literal past 64 KB, and an array is not one.

    python3 tools/make-font.py [path/to/RobotoCondensed[wght].ttf]

Needs Pillow (with FreeType variation support), numpy and scipy. The output
is committed: the build does not run this.
"""

import pathlib
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy import ndimage

REPO = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_FONT = pathlib.Path.home() / "Library/Fonts/google-fonts/ofl/robotocondensed/RobotoCondensed[wght].ttf"

EM = 32          # pixels per em in the atlas
SPREAD = 8       # pixels of distance field either side of the outline
CELL_W = 44
CELL_H = 56
COLUMNS = 16
FIRST = 32
COUNT = 96       # 32..127; 127 is left blank
SUPER = 8        # supersampling of the outline before the distance transform
WEIGHT = 300     # Light


def main():
    font_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_FONT
    big = ImageFont.truetype(str(font_path), EM * SUPER)
    big.set_variation_by_axes([WEIGHT])
    ascent, descent = big.getmetrics()

    # The baseline sits so the descender and the ascender both fit, with the
    # spread clear of both edges.
    baseline = SPREAD + round(ascent / SUPER)
    if baseline + round(descent / SUPER) + SPREAD > CELL_H:
        sys.exit(f"cell too short: ascent {ascent / SUPER} + descent {descent / SUPER} + 2 x {SPREAD}")
    pen_x = SPREAD

    rows = (COUNT + COLUMNS - 1) // COLUMNS
    atlas = np.zeros((rows * CELL_H, COLUMNS * CELL_W), dtype=np.uint8)
    advances = []
    widest = 0.0
    for index in range(COUNT):
        code = FIRST + index
        cell = np.zeros((CELL_H, CELL_W), dtype=np.uint8)
        if code < 127:
            ch = chr(code)
            advance = big.getlength(ch) / SUPER
            advances.append(advance / EM)
            widest = max(widest, advance)
            image = Image.new("L", (CELL_W * SUPER, CELL_H * SUPER), 0)
            ImageDraw.Draw(image).text((pen_x * SUPER, baseline * SUPER), ch, font=big, fill=255, anchor="ls")
            inside = np.asarray(image) >= 128
            if inside[:SUPER, :].any() or inside[-SUPER:, :].any() or inside[:, :SUPER].any() or inside[:, -SUPER:].any():
                sys.exit(f"glyph {ch!r} touches its cell's edge")
            if inside.any():
                outside_d = ndimage.distance_transform_edt(~inside)
                inside_d = ndimage.distance_transform_edt(inside)
                signed = (inside_d - outside_d) / SUPER
            else:
                signed = np.full(inside.shape, -float(SPREAD), dtype=np.float64)
            # The value at each atlas pixel's centre.
            centres = signed[SUPER // 2::SUPER, SUPER // 2::SUPER]
            cell = np.clip(np.round((0.5 + centres / (2.0 * SPREAD)) * 255.0), 0, 255).astype(np.uint8)
        else:
            advances.append(0.0)
        r, c = divmod(index, COLUMNS)
        atlas[r * CELL_H:(r + 1) * CELL_H, c * CELL_W:(c + 1) * CELL_W] = cell

    if widest + 2 * SPREAD > CELL_W:
        sys.exit(f"cell too narrow: widest advance {widest:.1f} px")

    # GL's rows run bottom up: flip so row 0 of the array is the texture's.
    texture = np.flipud(atlas)
    height, width = texture.shape
    flat = texture.reshape(-1)

    out = []
    out.append("// GENERATED by tools/make-font.py -- do not edit. Roboto Condensed Light,")
    out.append("// SIL Open Font License 1.1 (fonts/OFL.txt), as a signed distance field.")
    out.append('#include "Font.h"')
    out.append("")
    out.append("namespace bluebook::font")
    out.append("{")
    out.append("const float kAdvance[ kCount ] = {")
    for i in range(0, COUNT, 8):
        out.append("\t" + ", ".join(f"{a:.6f}f" for a in advances[i:i + 8]) + ",")
    out.append("};")
    out.append("")
    out.append(f"const unsigned char kAtlas[ kAtlasWidth * kAtlasHeight ] = {{")
    for i in range(0, len(flat), 32):
        out.append("\t" + ",".join(str(int(v)) for v in flat[i:i + 32]) + ",")
    out.append("};")
    out.append("} // namespace bluebook::font")
    (REPO / "source/FontAtlas.cpp").write_text("\n".join(out) + "\n")

    header_constants = {
        "kEm": EM, "kSpread": SPREAD, "kCellWidth": CELL_W, "kCellHeight": CELL_H,
        "kColumns": COLUMNS, "kFirst": FIRST, "kCount": COUNT,
        "kAtlasWidth": width, "kAtlasHeight": height,
        "kBaseline": baseline, "kPenX": pen_x,
    }
    print(" ".join(f"{k}={v}" for k, v in header_constants.items()))
    print(f"cap height {big.getbbox('H')[3] - big.getbbox('H')[1]} / {SUPER} px; ascent {ascent / SUPER:.1f}, descent {descent / SUPER:.1f}")


if __name__ == "__main__":
    main()
